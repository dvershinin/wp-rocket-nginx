if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

// phpcs:disable WordPress.Security.EscapeOutput.OutputNotEscaped -- This template renders an Nginx configuration file, not HTML. Every value is sanitized for Nginx syntax by Settings_Reader before it reaches this scope.
?>
###################################################################################################
# GetPageSpeed Cache Configuration
#
# Serves WP Rocket cache files directly from Nginx without loading PHP.
# Generated by https://github.com/dvershinin/getpagespeed-cache-configuration
# Based on Rocket-Nginx 3.1.2 by Maxime Jobin and SatelliteWP.
###################################################################################################

set $rocket_debug <?php echo (int) $debug; ?>;

set $rocket_bypass          1;
set $rocket_encryption      "";
set $rocket_file            "";
set $rocket_is_bypassed     "MISS";
set $rocket_reason          "";
set $rocket_https_prefix    "";
set $rocket_mobile_prefix   "";
set $rocket_is_https        0;
set $rocket_dynamic         "";
set $rocket_device          "desktop";

# Custom start includes.
<?php echo $include_start; ?>

# Preserve whether the original request contains arguments and extract its URI path.
set $rocket_is_args $is_args;
set $rocket_uri_path $request_uri;
if ($request_uri ~* "^([^?]*)(\?.+)$") {
    set $rocket_uri_path $1;
}

# Prefer WP Rocket's pre-compressed gzip file unless Brotli is available.
if ($http_accept_encoding ~ gzip) {
    set $rocket_encryption "_gzip";
}
if ($http_accept_encoding ~ br) {
    set $rocket_encryption "";
}

# Detect HTTPS directly and behind common reverse proxies.
if ($https = "on") { set $rocket_is_https 1; }
if ($http_x_forwarded_proto = "https") { set $rocket_is_https 1; }
if ($http_front_end_https = "on") { set $rocket_is_https 1; }
if ($http_x_forwarded_protocol = "https") { set $rocket_is_https 1; }
if ($http_x_forwarded_ssl = "on") { set $rocket_is_https 1; }
if ($http_x_url_scheme = "https") { set $rocket_is_https 1; }
if ($http_forwarded ~ /proto=https/) { set $rocket_is_https 1; }
if ($rocket_is_https = "1") {
    set $rocket_https_prefix "-https";
}

# Strip non-content-changing query parameters.
<?php echo $query_string_ignore; ?>

if ($rocket_args = "") {
    set $rocket_is_args "";
}

# Map query strings configured for caching to WP Rocket's #argument directory.
<?php echo $query_string_cache; ?>

# Issue #232 regression fix: build the mobile marker from the URI path and the
# normalized/cache-mapped arguments, never from raw $request_uri containing '?'.
set $rocket_mobile_detection "$document_root/<?php echo $wp_content_uri; ?>/cache/wp-rocket/$http_host/$rocket_uri_path/$rocket_args/.mobile-active";

if ($http_user_agent ~* "<?php echo $mobile_user_agent; ?>") {
    set $rocket_device "mobile";
}
if (-f "$rocket_mobile_detection") {
    set $rocket_mobile_prefix "-mobile";
}
if ($rocket_device != "mobile") {
    set $rocket_mobile_prefix "";
}

set $rocket_file_start "index$rocket_mobile_prefix$rocket_https_prefix";

# Custom preprocess includes may change $rocket_uri_path or $rocket_dynamic.
<?php echo $include_preprocess; ?>

set $rocket_pre_url "/<?php echo $wp_content_uri; ?>/cache/wp-rocket/$http_host/$rocket_uri_path/$rocket_args/";
set $rocket_pre_file "$document_root/<?php echo $wp_content_uri; ?>/cache/wp-rocket/$http_host/$rocket_uri_path/$rocket_args/";
set $rocket_url "$rocket_pre_url$rocket_file_start$rocket_dynamic.html";
set $rocket_file "$rocket_pre_file$rocket_file_start$rocket_dynamic.html";

if (-f "$rocket_file$rocket_encryption") {
    set $rocket_file "$rocket_file$rocket_encryption";
    set $rocket_url "$rocket_url$rocket_encryption";
}

if (!-f "$rocket_file") {
    set $rocket_bypass 0;
    set $rocket_is_bypassed "MISS";
    set $rocket_reason "File not cached";
}
if ($request_method = POST) {
    set $rocket_bypass 0;
    set $rocket_is_bypassed "BYPASS";
    set $rocket_reason "POST request";
}
if ($rocket_is_args) {
    set $rocket_bypass 0;
    set $rocket_is_bypassed "BYPASS";
    set $rocket_reason "Arguments found";
}
if (-f "$document_root/.maintenance") {
    set $rocket_bypass 0;
    set $rocket_is_bypassed "BYPASS";
    set $rocket_reason "Maintenance mode";
}
if ($http_cookie ~* "(<?php echo $cookie_invalidate; ?>)") {
    set $rocket_bypass 0;
    set $rocket_is_bypassed "BYPASS";
    set $rocket_reason "Cookie";
}

if ($rocket_bypass = 1) {
    set $rocket_is_bypassed "HIT";
    set $rocket_reason "$rocket_url";
}
if ($rocket_debug = 0) {
    set $rocket_reason "";
    set $rocket_file "";
    set $rocket_device "";
}
if ($rocket_bypass = 1) {
    rewrite .* "$rocket_url" last;
}

# Generated configuration files live in the uploads directory by default.
# Never serve them, or files left in the pre-1.2.0 location, to HTTP clients.
location ~* /(?:getpagespeed-cache-configuration|wp-rocket-nginx)/.*\.conf$ {
    deny all;
}

location ~ /<?php echo $wp_content_uri; ?>/cache/wp-rocket/.*html$ {
    etag on;
    add_header Vary "Accept-Encoding, Cookie";
    add_header Cache-Control "<?php echo $html_cache_control; ?>";
    add_header X-Rocket-Nginx-Serving-Static $rocket_is_bypassed always;
    add_header X-Rocket-Nginx-Reason $rocket_reason always;
    add_header X-Rocket-Nginx-File $rocket_file always;
    add_header X-Rocket-Nginx-Device $rocket_device always;

    <?php echo $include_global; ?>
    <?php echo $include_http; ?>
}

location ~ /<?php echo $wp_content_uri; ?>/cache/wp-rocket/.*_gzip$ {
    etag on;
    gzip off;
    types {}
    default_type text/html;
    add_header Content-Encoding gzip;
    add_header Vary "Accept-Encoding, Cookie";
    add_header Cache-Control "<?php echo $html_cache_control; ?>";
    add_header X-Rocket-Nginx-Serving-Static $rocket_is_bypassed always;
    add_header X-Rocket-Nginx-Reason $rocket_reason always;
    add_header X-Rocket-Nginx-File $rocket_file always;
    add_header X-Rocket-Nginx-Device $rocket_device always;

    <?php echo $include_global; ?>
    <?php echo $include_http; ?>
}

add_header X-Rocket-Nginx-Serving-Static $rocket_is_bypassed always;
add_header X-Rocket-Nginx-Reason $rocket_reason always;
add_header X-Rocket-Nginx-File $rocket_file always;
add_header X-Rocket-Nginx-Device $rocket_device always;

<?php echo $include_global; ?>

# Nginx serves static assets directly from disk.
location ~* \.css$ {
    etag on;
    gzip_vary on;
    expires <?php echo $css_expiration; ?>;

    <?php echo $include_global; ?>
    <?php echo $include_css; ?>
}

location ~* \.js$ {
    etag on;
    gzip_vary on;
    expires <?php echo $js_expiration; ?>;

    <?php echo $include_global; ?>
    <?php echo $include_js; ?>
}

location ~* \.(<?php echo $media_extensions; ?>)$ {
    etag on;
    expires <?php echo $media_expiration; ?>;

    <?php echo $include_global; ?>
    <?php echo $include_media; ?>
}
